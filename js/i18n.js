const nodes = () => document.querySelectorAll('[data-i18n]');
let captured = false;
function captureEnglish(){
  if (captured) return; captured = true;
  nodes().forEach(el => { if (!(el.dataset.i18n in STR.en)) STR.en[el.dataset.i18n] = el.textContent; });
}

export function setLang(lang){
  captureEnglish();
  const d = STR[lang] ? lang : 'en';
  const root = document.documentElement;
  root.lang = d; root.dir = d === 'he' ? 'rtl' : 'ltr';
  nodes().forEach(el => { const v = STR[d][el.dataset.i18n]; if (v != null) el.textContent = v; });
  document.querySelectorAll('[data-lang]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === d)));
  try { localStorage.setItem('bzik-lang', d); } catch (e) {}
  return d;
}

export function initialLang(){
  try { const s = localStorage.getItem('bzik-lang'); if (s) return s; } catch (e) {}
  return (navigator.language || '').toLowerCase().startsWith('he') ? 'he' : 'en';
}

export function missingKeys(){
  captureEnglish();
  return Object.keys(STR.en).filter(k => !(k in STR.he));
}
